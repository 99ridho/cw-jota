// Builds the mystery word pools from Faker's English word lists plus the
// curated seeds below, then writes src/lib/morse/wordPools.ts.
// Faker stays a dev dependency: the app only ships the generated lists.
import { writeFileSync } from 'node:fs'
import { fakerEN } from '@faker-js/faker'
import { STAGES, stageChars, stageNew } from '../src/lib/morse/table.ts'

const OUT = new URL('../src/lib/morse/wordPools.ts', import.meta.url)
const MIN_LEN = 3
const MAX_LEN = 6

const SEEDS = {
  1: [
    'SOS', 'SEA', 'NOTE', 'STONE', 'MEAT', 'TEAM', 'NAME', 'MOON', 'ONSET', 'MEAN',
    'MAT', 'NET', 'TEN', 'SET', 'EAT', 'SEAT', 'MOST', 'NEST', 'TOAST',
    'SON', 'TONE', 'MANE', 'STEAM', 'MASON', 'NOON', 'OATS', 'TOES', 'MESS', 'TOTEM',
  ],
  2: [
    'RADIO', 'KING', 'WIND', 'DRUM', 'GRID', 'TIGER', 'WORD', 'DOG', 'RING', 'SKI',
    'DUST', 'GUARD', 'MOUSE', 'WAGON', 'STORM', 'RAIN', 'SNOW', 'WATER', 'GAME', 'KITE',
    'RIDE', 'TRAIN', 'DREAM', 'GOAT', 'SUN',
  ],
  3: [
    'FISH', 'HELP', 'CLUB', 'PLANE', 'BLUE', 'VAN', 'CAMP', 'FLAG', 'HIKE', 'TORCH',
    'BEACH', 'CLIMB', 'HILL', 'FIRE', 'LAMP', 'BOAT', 'CAVE', 'MAP', 'SHIP', 'BELL',
    'PATROL', 'FOREST', 'VOICE', 'PHONE', 'LIGHT',
  ],
  4: [
    'JOTA', 'QUIZ', 'BOX', 'FOX', 'ZOO', 'JAM', 'SKY', 'KEY', 'YES', 'JUNGLE',
    'PIZZA', 'ZEBRA', 'JUMP', 'QUEEN', 'SIX', 'TAXI', 'YOUTH', 'JOY', 'ZIP', 'EXIT',
    'JACKET', 'QUICK', 'ZONE', 'YELLOW', 'JAZZ',
  ],
  medium: [
    'RADIO', 'CAMP', 'TENT', 'KNOT', 'SCOUT', 'WAVE', 'FIRE', 'FLAG', 'ROPE', 'HIKE',
    'JOTA', 'MAP', 'SKY', 'BUS', 'KEY', 'HELLO', 'BADGE', 'TORCH', 'RIVER', 'FOX',
    'JAM', 'ZOO', 'QUIZ', 'WOLF', 'BOX', 'GPS', 'VOICE', 'PIZZA', 'JUNGLE', 'LIGHT',
  ],
}

// Words a scout leader would not want on the screen of a kid's phone, then
// archaic words, jargon, brands, and sounds with no settled spelling, which a
// first-timer could not guess from the letters heard.
const BLOCK = new Set([
  'ARSE', 'ASS', 'BIDET', 'BOOZE', 'BUTT', 'CURSE', 'DAMN', 'DEVIL', 'DRUG', 'DRUNK',
  'HELL', 'KILL', 'KISS', 'LOUSE', 'NUDE', 'PERP', 'SCREW', 'SEX', 'SEXY', 'SINFUL',
  'SUCKLE', 'SWINE', 'THIGH', 'THONGS',
  'ABAFT', 'AFORE', 'AIRBUS', 'ANENST', 'APUD', 'BRR', 'DEFRAG', 'DEMOB', 'DEPUTE',
  'ELVER', 'ETHYL', 'FESS', 'GAD', 'GAH', 'GROK', 'GURN', 'HMPH', 'HOICK', 'HORST',
  'KINASE', 'LIEU', 'LIGATE', 'MANTUA', 'MISKEY', 'MMM', 'MODULO', 'PER', 'PFFT',
  'PISH', 'PLUGIN', 'PSST', 'QUA', 'SANS', 'SKEAN', 'SUV', 'VOL', 'WHUP', 'WOOT',
])

const faker = [...new Set(
  Object.values(fakerEN.definitions.word).flat().map((w) => w.toUpperCase()),
)].filter((w) => new RegExp(`^[A-Z]{${MIN_LEN},${MAX_LEN}}$`).test(w) && !BLOCK.has(w))

const sorted = (words) => [...new Set(words)].sort((a, b) => a.length - b.length || a.localeCompare(b))

const easy = {}
for (let stage = 1; stage <= STAGES.length; stage++) {
  const known = new Set(stageChars(stage))
  const fresh = stageNew(stage)
  const fits = (w) => [...w].every((c) => known.has(c)) && (stage === 1 || [...w].some((c) => fresh.includes(c)))
  easy[stage] = sorted([...SEEDS[stage], ...faker.filter(fits)])
}
const medium = sorted([...SEEDS.medium, ...faker])

const list = (words) => words.map((w) => `'${w}'`).join(', ')
writeFileSync(OUT, `// Generated by scripts/gen-words.mjs (npm run gen:words). Do not edit.

export const EASY_POOLS: Record<number, string[]> = {
${Object.entries(easy).map(([s, w]) => `  ${s}: [${list(w)}],`).join('\n')}
}

export const MEDIUM_POOL: string[] = [${list(medium)}]
`)

for (const [s, w] of Object.entries(easy)) console.log(`easy ${s}: ${w.length}`)
console.log(`medium: ${medium.length}`)
